/**
 * Prebuild script: reads content/blog/*.mdx and writes lib/generated-blog-data.ts
 * Runs as part of `npm run build` so Cloudflare Pages picks it up automatically.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { createRequire } from "module";

const require = createRequire(import.meta.url);
const matter = require("gray-matter");

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const blogDir = path.join(__dirname, "..", "content", "blog");
const outputFile = path.join(__dirname, "..", "lib", "generated-blog-data.ts");

if (!fs.existsSync(blogDir)) {
  fs.writeFileSync(
    outputFile,
    "// Auto-generated by scripts/generate-blog-data.mjs\nexport const BLOG_FILES_RAW: { filename: string; frontmatter: Record<string, unknown>; content: string }[] = [];\n"
  );
  console.log("No content/blog directory found. Generated empty data file.");
  process.exit(0);
}

const files = fs
  .readdirSync(blogDir)
  .filter((f) => f.endsWith(".mdx"))
  .sort();

const entries = files.map((filename) => {
  const raw = fs.readFileSync(path.join(blogDir, filename), "utf8");
  const { data, content } = matter(raw);
  return { filename, frontmatter: data, content };
});

const output = `// Auto-generated by scripts/generate-blog-data.mjs — do not edit manually
// Re-run \`npm run generate-blog\` after adding or editing blog posts
export const BLOG_FILES_RAW: { filename: string; frontmatter: Record<string, unknown>; content: string }[] = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(outputFile, output);
console.log(`Generated blog data for ${files.length} post(s): ${files.join(", ")}`);
