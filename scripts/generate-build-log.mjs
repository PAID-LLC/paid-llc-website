/**
 * Prebuild script: reads recent git history and writes lib/generated-build-log.ts
 * for the Iteration Forge floor's signature exhibit — the site's own build log
 * rendered as the forge's output. Runs alongside generate-blog-data.mjs in
 * `npm run dev` / `npm run build` so Cloudflare Pages picks it up.
 *
 * Fallbacks, in order: git log → CF_PAGES_COMMIT_SHA single entry → keep the
 * committed file as-is (it's checked in, so a shallow clone still ships a log).
 */
import fs from "fs";
import path from "path";
import { execSync } from "child_process";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputFile = path.join(__dirname, "..", "lib", "generated-build-log.ts");

function write(entries) {
  const body =
    "// Auto-generated by scripts/generate-build-log.mjs — do not edit.\n" +
    "// The Iteration Forge floor renders this as the forge's output.\n" +
    "export interface BuildLogEntry { sha: string; date: string; subject: string }\n" +
    `export const BUILD_LOG: BuildLogEntry[] = ${JSON.stringify(entries, null, 2)};\n`;
  fs.writeFileSync(outputFile, body);
  console.log(`Generated build log with ${entries.length} entr${entries.length === 1 ? "y" : "ies"}.`);
}

try {
  const raw = execSync('git log -12 --pretty=format:"%h%cs%s"', {
    cwd: path.join(__dirname, ".."),
    encoding: "utf8",
  });
  const entries = raw
    .split("\n")
    .filter(Boolean)
    .map((line) => {
      const [sha, date, subject] = line.split("");
      return { sha, date, subject: (subject ?? "").slice(0, 90) };
    })
    .filter((e) => e.sha && e.date);
  if (entries.length === 0) throw new Error("empty git log");
  write(entries);
} catch {
  const sha = (process.env.CF_PAGES_COMMIT_SHA ?? "").slice(0, 7);
  if (sha) {
    write([{ sha, date: new Date().toISOString().slice(0, 10), subject: "current build" }]);
  } else if (fs.existsSync(outputFile)) {
    console.log("git log unavailable — keeping committed build log.");
  } else {
    write([]);
  }
}
